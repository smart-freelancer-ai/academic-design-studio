// وظائف مساعدة للبحث في المكتبة
export const searchContent = (category, keyword) => {
  if (!contentLibrary[category]) return [];
  
  const categoryData = contentLibrary[category];
  const results = [];
  
  Object.keys(categoryData).forEach(subCategory => {
    if (Array.isArray(categoryData[subCategory])) {
      const matches = categoryData[subCategory].filter(item => 
        item.toLowerCase().includes(keyword.toLowerCase())
      );
      if (matches.length > 0) {
        results.push({ subCategory, matches });
      }
    }
  });
  
  return results;
};

// الحصول على اقتراحات عشوائية
export const getRandomSuggestions = (category, count = 5) => {
  if (!contentLibrary[category]) return [];
  
  const categoryData = contentLibrary[category];
  const allItems = [];
  
  Object.values(categoryData).forEach(items => {
    if (Array.isArray(items)) {
      allItems.push(...items);
    }
  });
  
  // خلط عشوائي واختيار عدد محدد
  const shuffled = allItems.sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
};

// استبدال المتغيرات في النصوص
export const replaceVariables = (text, variables = {}) => {
  let result = text;
  Object.keys(variables).forEach(key => {
    const placeholder = `{${key}}`;
    result = result.replace(new RegExp(placeholder, 'g'), variables[key]);
  });
  return result;
};
